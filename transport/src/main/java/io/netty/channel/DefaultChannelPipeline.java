    @Override
    public final ChannelPipeline addLast(EventExecutorGroup group, String name, ChannelHandler handler) {
        final AbstractChannelHandlerContext newCtx;
        // 线程同步，因为channel可能被暴露给用户线程，所以要做并发控制
        synchronized (this) {
            // 检查handler是否能被多次添加到流水线中
            checkMultiplicity(handler);

            /*
             * 创建ChannelHandlerContext，封装handler。
             * 这里如果指定了name（不是null），那么直接检查名称是否重复了
             * 如果没有指定name，则先生成名称
             *
             * 名称检查是会遍历pipeline中的所有context
             */
            newCtx = newContext(group, filterName(name, handler), handler);

            // 本质上就是一个双向链表的插入操作
            addLast0(newCtx);

            // If the registered is false it means that the channel was not registered on an eventLoop yet.
            // In this case we add the context to the pipeline and add a task that will call
            // ChannelHandler.handlerAdded(...) once the channel is registered.
            /*
             * 如果通道还未注册过
             */
            if (!registered) {
                // 修改其状态
                newCtx.setAddPending();
                // 封装延迟任务并添加到延迟任务链表中
                callHandlerCallbackLater(newCtx, true);
                return this;
            }

            EventExecutor executor = newCtx.executor();
            /*
             * 如果当前线程是事件循环中的线程，那么提前退出同步块，缓解线程因锁产生的竞争。
             */
            if (!executor.inEventLoop()) {
                // 执行添加handler的回调
                callHandlerAddedInEventLoop(newCtx, executor);
                return this;
            }
        }

        // 回调用户方法和设置状态
        callHandlerAdded0(newCtx);
        return this;
    }
    // SNIPPET_END addLast_1_2

    // SNIPPET_START addLast0
    private void addLast0(AbstractChannelHandlerContext newCtx) {
        AbstractChannelHandlerContext prev = tail.prev;
        newCtx.prev = prev;
        newCtx.next = tail;
        prev.next = newCtx;
        tail.prev = newCtx;
    }
    // SNIPPET_END addLast0

