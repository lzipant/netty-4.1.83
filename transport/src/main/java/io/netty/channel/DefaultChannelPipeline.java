    // SNIPPET_START context0
    private AbstractChannelHandlerContext context0(String name) {
        // 从头结点开始遍历
        AbstractChannelHandlerContext context = head.next;
        // 遍历通道处理器上下文对象
        while (context != tail) {
            // 如果链表中已经存在相同名称的节点了
            if (context.name().equals(name)) {
                // 返回相同名称的通道上下文对象
                return context;
            }
            // 推动往后遍历
            context = context.next;
        }
        return null;
    }
