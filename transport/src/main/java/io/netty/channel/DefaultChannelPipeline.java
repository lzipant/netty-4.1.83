    // SNIPPET_START filterName
    private String filterName(String name, ChannelHandler handler) {
        if (name == null) { // 如果名称为null
            // 则生成名称，内部已包含重复性检查
            return generateName(handler);
        }
        // 检查名称是否重复
        checkDuplicateName(name);
        return name;
    }
