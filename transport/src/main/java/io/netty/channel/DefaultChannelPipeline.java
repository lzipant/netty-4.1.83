    // SNIPPET_START callHandlerAddedForAllHandlers
    private void callHandlerAddedForAllHandlers() {
        // 临时变量
        final PendingHandlerCallback pendingHandlerCallbackHead;
        synchronized (this) {
            assert !registered;

            // This Channel itself was registered.
            // 修改属性表示通道已经注册到该流水线中了。
            registered = true;

            pendingHandlerCallbackHead = this.pendingHandlerCallbackHead;
            // Null out so it can be GC'ed.
            // 重置链表头，当前是在同步块中，是线程安全的
            this.pendingHandlerCallbackHead = null;
        }

        // This must happen outside of the synchronized(...) block as otherwise handlerAdded(...) may be called while
        // holding the lock and so produce a deadlock if handlerAdded(...) will try to add another handler from outside
        // the EventLoop.
        // 执行任务链表中的任务
        PendingHandlerCallback task = pendingHandlerCallbackHead;
        while (task != null) {
            // 执行任务
            task.execute();
            task = task.next;
        }
    }
    // SNIPPET_END callHandlerAddedForAllHandlers

    // SNIPPET_START callHandlerCallbackLater
    private void callHandlerCallbackLater(AbstractChannelHandlerContext ctx, boolean added) {
        assert !registered;

        // 创建任务对象
        PendingHandlerCallback task = added ? new PendingHandlerAddedTask(ctx) : new PendingHandlerRemovedTask(ctx);
        // 获取链表头
        PendingHandlerCallback pending = pendingHandlerCallbackHead;
        if (pending == null) { // 如果链表没被初始化
            // 则初始化链表
            pendingHandlerCallbackHead = task;
        } else {
            // Find the tail of the linked-list.
            // 尾插法：将任务对象添加到链表中
            while (pending.next != null) {
                pending = pending.next;
            }
            pending.next = task;
        }
    }
    // SNIPPET_END callHandlerCallbackLater

    // SNIPPET_START callHandlerAddedInEventLoop
    private void callHandlerAddedInEventLoop(final AbstractChannelHandlerContext newCtx, EventExecutor executor) {
        // 修改其状态为ADD_PENDING，表示正在添加中
        newCtx.setAddPending();
        executor.execute(new Runnable() {
            @Override
            public void run() {
                callHandlerAdded0(newCtx);
            }
        });
    }
